import {createGame,addObject,moveObject,validateGame} from './game-state.mjs';
import assert from 'node:assert/strict';
let s=createGame(['A','B']);
assert.equal(s.players.A.life,20);
assert.throws(()=>createGame(['A','A']));
const added=addObject(s,{name:'Test creature',owner:'A',zone:'hand',types:['creature'],basePower:2,baseToughness:2});
s=added.state;
assert.equal(s.zones.hand.length,1);
assert.equal(validateGame(s).ok,true);
const moved=moveObject(s,added.id,'battlefield');
assert.equal(moved.zones.hand.length,0);
assert.equal(moved.zones.battlefield[0],added.id);
assert.equal(s.zones.hand.length,1,'Original state remains unchanged');
assert.equal(validateGame(moved).ok,true);
assert.throws(()=>moveObject(s,added.id,'unknown'));
assert.throws(()=>moveObject(s,added.id,'hand'));
assert.throws(()=>addObject(s,{name:'x',owner:'C'}));
assert.equal(moved.events.length,1);
console.log('Foundation tests passed');
