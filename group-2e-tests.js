(function(root){'use strict';
function run(){const tests=[],check=(name,ok)=>tests.push({name,pass:!!ok});
const o={id:'x',name:'X',types:['creature'],subtypes:[],supertypes:[],abilities:[],owner:'A',controller:'A',zone:'battlefield',power:2,toughness:4,counters:{}};
const e=(id,kind,layer,power,toughness,timestamp)=>({id,kind,layer,power,toughness,timestamp,targetId:'x'});
const runEffects=(effects,object=o,board=[])=>root.JudgeUnifiedContinuous.evaluate([object,...board],effects);
const set=runEffects([e('set','setPT','7b',5,6,1)]);
check('7b replaces printed PT',set.supported&&set.objects[0].power===5&&set.objects[0].toughness===6);
const mod=runEffects([e('set','setPT','7b',5,6,1),e('mod','modifyPT','7c',2,-3,2)]);
check('7c modifies 7b',mod.supported&&mod.objects[0].power===7&&mod.objects[0].toughness===3);
const plus=runEffects([e('mod','modifyPT','7c',2,-1,1)],{...o,counters:{'+1/+1':3,'-1/-1':1}});
check('counters applied in 7c',plus.supported&&plus.objects[0].power===6&&plus.objects[0].toughness===5);
const switched=runEffects([e('mod','modifyPT','7c',2,0,1),{id:'swap',kind:'switchPT',layer:'7d',timestamp:2,targetId:'x'}],{...o,counters:{'+1/+1':1}});
check('7d switches after counters',switched.supported&&switched.objects[0].power===5&&switched.objects[0].toughness===5);
const multiple=runEffects([e('one','setPT','7b',7,8,1),e('two','setPT','7b',3,9,2)]);
check('7b multiple setters follow timestamps',multiple.supported&&multiple.objects[0].power===3&&multiple.objects[0].toughness===9);
const doubleSwitch=runEffects([{id:'a',kind:'switchPT',layer:'7d',timestamp:1,targetId:'x'},{id:'b',kind:'switchPT',layer:'7d',timestamp:2,targetId:'x'}]);
check('two 7d switches cancel',doubleSwitch.supported&&doubleSwitch.objects[0].power===2&&doubleSwitch.objects[0].toughness===4);
const land={...o,id:'land',types:['land'],power:null,toughness:null};
const dynamic={...o,abilities:[{id:'pt',origin:'rulesText'}],ptDefinition:{kind:'landCount',abilityId:'pt'},power:0,toughness:0};
const dyn=runEffects([e('mod','modifyPT','7c',2,3,1)],dynamic,[land]);
check('7a dynamic land count with 7c',dyn.supported&&dyn.objects[0].power===3&&dyn.objects[0].toughness===4);
const override=runEffects([e('set','setPT','7b',6,7,1)],dynamic,[land]);
check('7b overrides dynamic 7a',override.supported&&override.objects[0].power===6&&override.objects[0].toughness===7);
const def=runEffects([e('def','definePT','7a',3,4,1),e('set','setPT','7b',9,8,2)]);
check('explicit 7a definition before 7b',def.supported&&def.objects[0].power===9&&def.objects[0].toughness===8);
const unknown=runEffects([], {...dynamic,ptDefinition:{kind:'unknown',abilityId:'pt'}});
check('unknown characteristic definition fails closed',!unknown.supported);
const invalid=runEffects([],{...o,counters:{'+1/+1':-1}});
check('negative counters fail closed',!invalid.supported);
const missing=runEffects([e('mod','modifyPT','7c',1,1,1)],{...o,power:null,toughness:null});
check('unknown base PT fails closed',!missing.supported);
const zero=runEffects([e('mod','modifyPT','7c',-3,-6,1)]);
check('zero or negative PT calculated before SBA',zero.supported&&zero.objects[0].power===-1&&zero.objects[0].toughness===-2);
check('source objects unchanged',o.power===2&&o.toughness===4&&Object.keys(o.counters).length===0);
return {passed:tests.filter(t=>t.pass).length,total:tests.length,tests};
}root.JudgeGroup2ETests={run};
})(typeof window!=='undefined'?window:globalThis);