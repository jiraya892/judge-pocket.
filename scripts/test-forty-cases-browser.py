"""Real Chromium UI and local Oracle; no simulated engine results."""
import os,shutil
from playwright.sync_api import sync_playwright, expect
origin=os.environ.get('JUDGE_TEST_ORIGIN','http://127.0.0.1:8000')
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path=None if os.environ.get('CI') else shutil.which('chromium'),headless=True,args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':390,'height':844},has_touch=True)
 # Pin snapshot regressions; source-update transports have their own tests.
 page.route('https://api.scryfall.com/**',lambda route:route.abort())
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 def begin(cards,event):
  page.goto(origin+'/context.html')
  for i,name in enumerate(cards):
   if i>=2:page.locator('#addCard').click()
   page.locator('[data-card-input]').nth(i).fill(name)
  page.locator('#begin').click();page.get_by_role('button',name=event,exact=True).click()
 def choose(name):page.locator('#choices').get_by_role('button',name=name,exact=True).click()
 def confirm():choose('Sì, considera soltanto queste carte')
 def result():
  page.wait_for_function("document.querySelector('#result').dataset.status === 'partial'")
  assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
  assert 'Regole applicate' in page.locator('#resultDetails').text_content()
 begin(['Colossal Dreadmaw','Darksteel Myr'],'Una creatura attaccante viene bloccata')
 choose('Colossal Dreadmaw');confirm()
 expect(page.locator('#choices').get_by_role('button')).to_have_count(6)
 choose('1 danno al bloccante');result()
 assert '5 danni' in page.locator('#status').inner_text()
 assert 'travolgere' in page.locator('#resultDetails').inner_text().lower()
 print('PASS UI: legal trample choice and actual player damage')
 page.locator('#moreContext').click()
 page.locator('#contextAnswerReview').get_by_role('button').filter(has_text='quanti danni').click()
 choose('6 danni al bloccante');result()
 assert 'non subisce danni' in page.locator('#status').inner_text()
 print('PASS UI: revise damage assignment and recompute without repeating roles')
 begin(['Swiftblade Vindicator','Darksteel Myr'],'Una creatura attaccante viene bloccata')
 choose('Swiftblade Vindicator');confirm();choose('0 danni al bloccante');result()
 assert '1 danno' in page.locator('#status').inner_text()
 print('PASS UI: double strike remembers prior marked damage')
 begin(['Phantom Warrior','Giant Spider'],'Posso bloccare questa creatura?')
 choose('Phantom Warrior');confirm();result()
 assert 'non può essere bloccata' in page.locator('#status').inner_text()
 print('PASS UI: cannot-be-blocked explained through legality query')
 begin(['Pyroclasm','Silver Knight'],'Sto lanciando una magia')
 choose('Pyroclasm');confirm();result()
 assert 'non bersaglia' in page.locator('#status').inner_text()
 assert 'danno viene prevenuto' in page.locator('#resultDetails').inner_text()
 print('PASS UI: untargeted spell and protection resolved on the real stack')
 begin(['Colossal Dreadmaw','Darksteel Myr','Archetype of Aggression'],'Una creatura attaccante viene bloccata')
 choose('Colossal Dreadmaw');choose('Darksteel Myr');confirm();choose('Il giocatore che blocca');result()
 assert 'non subisce danni' in page.locator('#status').inner_text()
 assert not errors,errors
 print('PASS UI: relevant controller asked; removing trample suppresses damage-choice question')
 begin(['Ridgetop Raptor','Darksteel Myr','Archetype of Aggression'],'Una creatura attaccante viene bloccata')
 choose('Ridgetop Raptor');choose('Darksteel Myr');confirm();choose('Il giocatore che attacca')
 choose('1 danno al bloccante');choose('0 danni al bloccante');result()
 assert '3 danni' in page.locator('#status').inner_text()
 page.locator('#moreContext').click()
 page.locator('#contextAnswerReview').get_by_role('button').filter(has_text='sottofase normale').click()
 expect(page.locator('#question')).to_contain_text('sottofase normale')
 choose('2 danni al bloccante');result()
 assert '1 danno' in page.locator('#status').inner_text()
 assert not errors,errors
 print('PASS UI: revising normal damage retains the answered first damage step')
 browser.close()
